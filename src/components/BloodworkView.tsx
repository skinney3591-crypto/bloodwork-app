import { AlertCircle, CheckCircle, ArrowUp, ArrowDown, Filter, Shield, Heart, Info, Upload, X, HelpCircle, Printer, Share2, CreditCard, TrendingUp, TrendingDown, Minus, ChevronDown, ChevronUp } from 'lucide-react'
import type { BloodworkResult } from '../data/mockData'
import { BarChart, Bar, XAxis, YAxis, CartesianGrid, Tooltip, ResponsiveContainer, Cell, LineChart, Line } from 'recharts'
import LabImport from './LabImport'
import { medicalTermDefinitions } from './MedicalTermTooltip'
